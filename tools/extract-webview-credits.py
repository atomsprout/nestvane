#!/usr/bin/env python3
"""Writes the license notices of Android System WebView as one HTML file: the credits page Chromium's
licenses.py generates, which the WebView package keeps brotli-compressed in assets/resources.pak. Nestvane
ships WebView, so the notices go inside the app (Licenses/NOTICE-WEBVIEW.html) and beside the release.

usage: extract-webview-credits.py <webview.apk> <output.html>
Decompresses with the system's Compression library (macOS)."""
import ctypes
import struct
import sys
import zipfile


def resources(pak):
    """The resources of a version 5 .pak file, by id."""
    version, = struct.unpack_from("<I", pak, 0)
    assert version == 5, "a .pak of version 5 expected"
    count, = struct.unpack_from("<H", pak, 8)
    entries = [struct.unpack_from("<HI", pak, 12 + 6 * index) for index in range(count + 1)]
    return {entries[index][0]: pak[entries[index][1]:entries[index + 1][1]] for index in range(count)}


def brotli(data):
    """A resource that Chromium's grit compressed with brotli: a two-byte mark, six bytes of size."""
    size = int.from_bytes(data[2:8], "little")
    library = ctypes.CDLL("/usr/lib/libcompression.dylib")
    library.compression_decode_buffer.restype = ctypes.c_size_t
    output = ctypes.create_string_buffer(size)
    written = library.compression_decode_buffer(output, size, data[8:], len(data) - 8, None, 0xB02)  # BROTLI
    assert written == size, "the notices did not decompress"
    return output.raw[:written]


def main():
    pak = zipfile.ZipFile(sys.argv[1]).read("assets/resources.pak")
    for data in resources(pak).values():
        if data[:2] != b"\x1e\x9b":
            continue
        text = brotli(data)
        if text.startswith(b"<!-- Generated by licenses.py"):
            open(sys.argv[2], "wb").write(text)
            print("%s: notices of %d components" % (sys.argv[2], text.count(b'class="product"')))
            return
    sys.exit("no license notices in the package")


if __name__ == "__main__":
    main()
